import { LanguageInfo, languageBySlug } from '../languages';
import { CodeSnippet, ProblemDetail, Site } from '../types/problem';
import { findCodeSnippet, problemUrl } from '../util/site';

export interface SolutionTemplate {
	language: LanguageInfo;
	fileName: string;
	content: string;
}

export interface AvailableLanguage {
	language: LanguageInfo;
	snippet: CodeSnippet;
}

export function availableLanguages(detail: ProblemDetail): AvailableLanguage[] {
	const available: AvailableLanguage[] = [];
	for (const snippet of detail.codeSnippets) {
		const language = languageBySlug(snippet.langSlug);
		if (language) {
			available.push({ language, snippet });
		}
	}
	return available;
}

export function buildSolutionTemplate(
	detail: ProblemDetail,
	site: Site,
	langSlug: string
): SolutionTemplate | undefined {
	const language = languageBySlug(langSlug);
	const snippet = findCodeSnippet(detail.codeSnippets, langSlug);
	if (!language || !snippet) {
		return undefined;
	}
	const prefix = language.commentPrefix;
	const header = [
		`${prefix} ${detail.questionFrontendId}. ${detail.title} (${detail.difficulty})`,
		`${prefix} ${problemUrl(site, detail.titleSlug)}`,
		`${prefix} Generated by Simple Leet. Keep the required signature when submitting.`,
	].join('\n');
	return {
		language,
		fileName: `solution${language.extension}`,
		content: `${header}\n\n${snippet.code.trimEnd()}\n`,
	};
}